export type I18nKey = keyof typeof AR;

export function t(key: I18nKey): string {
  return (AR as any)[key] || key;
}

export function formatCurrency(amount: number, symbol?: string): string {
  const sym = symbol || AR.currency_symbol;
  const abs = Math.abs(amount);
  const formatted = abs.toLocaleString('ar-SA', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  });
  const sign = amount < 0 ? '-' : '';
  return `${sign}${formatted} ${sym}`;
}

export function formatDate(dateStr: string): string {
  try {
    return new Date(dateStr).toLocaleDateString('ar-SA', {
      year: 'numeric', month: 'short', day: 'numeric',
    });
  } catch { return dateStr; }
}

export function formatDateTime(dateStr: string): string {
  try {
    return new Date(dateStr).toLocaleString('ar-SA', {
      year: 'numeric', month: 'short', day: 'numeric',
      hour: '2-digit', minute: '2-digit',
    });
  } catch { return dateStr; }
}

export function getToday(): string {
  return new Date().toISOString().split('T')[0];
}

export function getDateRange(period: string): { from: string; to: string } {
  const now = new Date();
  const todayStr = getToday();
  if (period === 'today') return { from: todayStr, to: todayStr };
  if (period === 'yesterday') {
    const d = new Date(now); d.setDate(d.getDate() - 1);
    const s = d.toISOString().split('T')[0];
    return { from: s, to: s };
  }
  if (period === 'week') {
    const start = new Date(now); start.setDate(now.getDate() - 6);
    return { from: start.toISOString().split('T')[0], to: todayStr };
  }
  if (period === 'month') {
    const start = new Date(now.getFullYear(), now.getMonth(), 1);
    return { from: start.toISOString().split('T')[0], to: todayStr };
  }
  if (period === 'year') {
    const start = new Date(now.getFullYear(), 0, 1);
    return { from: start.toISOString().split('T')[0], to: todayStr };
  }
  return { from: todayStr, to: todayStr };
}

export function getTransactionTypeLabel(type: string): string {
  const map: Record<string, string> = {
    cash_sale: AR.type_cash_sale,
    credit_sale: AR.type_credit_sale,
    collection: AR.type_collection,
    expense: AR.type_expense,
    purchase: AR.type_purchase,
    payment: AR.type_payment,
    cash: AR.type_cash_sale,
    credit: AR.type_credit_sale,
  };
  return map[type] || type;
}

export function daysFromToday(dateStr: string): number {
  const diff = new Date(dateStr).getTime() - new Date(getToday()).getTime();
  return Math.ceil(diff / (1000 * 60 * 60 * 24));
}

export function expiryLabel(days: number): string {
  if (days <= 0) return 'منتهية الصلاحية';
  if (days === 1) return 'تنتهي غداً';
  if (days <= 30) return `تنتهي خلال ${days} يوم`;
  if (days <= 60) return `تنتهي خلال شهرين`;
  if (days <= 90) return `تنتهي خلال 3 أشهر`;
  return `تنتهي ${formatDate(new Date(Date.now() + days * 86400000).toISOString().split('T')[0])}`;
}
